"""Static conformance: does the oracle reproduce the golden vectors byte for byte?

The vectors were generated by the TypeScript core; this file was written from spec/CANON.md
and spec/CORE-FORMAT.md. So a pass here is agreement between two implementations, not a
transcription check.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from graphmap_oracle import canon_hex, h, prim_unit, unit_id, graph_hash, load_workspace
from graphmap_oracle.workspace import from_spec

SPEC = Path(__file__).resolve().parent.parent / "spec" / "vectors"


def check_canon() -> list[str]:
    bad = []
    data = json.loads((SPEC / "canon.json").read_text())
    for c in data["cases"]:
        v = from_spec(c["value"])
        got_enc, got_hash = canon_hex(v), h(v)
        if got_enc != c["enc"]:
            bad.append(f"canon/{c['name']}: enc {got_enc} != {c['enc']}")
        if got_hash != c["hash"]:
            bad.append(f"canon/{c['name']}: hash {got_hash} != {c['hash']}")
    return bad


def check_units() -> list[str]:
    bad = []
    data = json.loads((SPEC / "units.json").read_text())
    for op, expected in data["primitives"].items():
        got = unit_id(prim_unit(op))
        if got != expected:
            bad.append(f"unit/{op}: {got} != {expected}")
    a, b = data["gauge"]["hashes"]
    if a != b:
        bad.append("gauge: the two wire orders were expected to hash identically")
    return bad


def check_ticks() -> list[str]:
    from run import run_scenario
    bad = []
    scen = json.loads((SPEC / "scenarios.json").read_text())["scenarios"]
    want = {r["name"]: r for r in json.loads((SPEC / "ticks.json").read_text())["results"]}
    for s in scen:
        got = run_scenario(s)
        exp = want[s["name"]]
        if got.get("error") or exp.get("error"):
            if got.get("error") != exp.get("error"):
                bad.append(f"{s['name']}: error {got.get('error')!r} != {exp.get('error')!r}")
            continue
        if got["graphHash"] != exp["graphHash"]:
            bad.append(f"{s['name']}: graphHash {got['graphHash']} != {exp['graphHash']}")
        for i, (g, e) in enumerate(zip(got["ticks"], exp["ticks"])):
            if g["sigmaHash"] != e["sigmaHash"]:
                bad.append(
                    f"{s['name']} tick {i}: sigmaHash differs\n"
                    f"    oracle {g['sigmaHash']}\n    core   {e['sigmaHash']}\n"
                    f"    sigma diff: {_diff(g['sigma'], e['sigma'])}"
                )
            if g["ran"] != e["ran"]:
                bad.append(f"{s['name']} tick {i}: ran {g['ran']} != {e['ran']}")
            if g["effects"] != e["effects"]:
                bad.append(f"{s['name']} tick {i}: effects {g['effects']} != {e['effects']}")
    return bad


def _diff(a: dict, b: dict) -> str:
    keys = sorted(set(a) | set(b))
    return "; ".join(f"{k}: {a.get(k, '-')[:14]} vs {b.get(k, '-')[:14]}"
                     for k in keys if a.get(k) != b.get(k)) or "(identical)"


def main() -> int:
    bad = check_canon() + check_units() + check_ticks()
    if bad:
        print(f"NOT CONFORMANT — {len(bad)} disagreement(s):")
        for b in bad:
            print("  -", b)
        return 1
    print("conformant: canon vectors, unit hashes, and every sigma agree with the core")
    return 0


if __name__ == "__main__":
    sys.exit(main())
